/** `bun run db:codegen [--check]`: queries (`src/queries/<area>.sql` → `.gen.ts`), migration and seed lists (`src/migrations/index.gen.ts`,
 * `src/seeds/index.gen.ts`) and table types (`src/tables/<table>.gen.ts`). Seam: core does not import these folders (the registry only
 * imports the lists); only this command reads and writes them. */
import { readdir, rm } from "node:fs/promises";
import { Glob } from "bun";
import { AppError } from "../errors";
import { checksum, compileMigrations, compileSeeds, MIGRATION_NAME, migrationPrefix, SOURCE_FILE } from "../migrations/source";
import type { TableColumns } from "./casing";
import { compile } from "./compiler";
import { foldTables, tableModules } from "./tables";

// The runtime does not re-validate SQL: only compiler output may produce a prepared query.
const mayDefineQuery = /^src\/core\/sql\/(compiler|query|codegen)\.ts$/;
/** Export names across the package: camelCase verb+noun, e.g. `createPasswordUser`. */
const QUERY_NAME = /^[a-z][A-Za-z0-9]*$/;
const QUERY_FILE = /^src\/queries\/[a-z0-9_-]+\.sql$/;

/** Compiles the `-- name: x` blocks of each query file (path, source) into its own module: module path → text. `tables`: migration tables (`*` expansion). */
export function generate(files: readonly (readonly [string, string])[], tables?: TableColumns): Map<string, string> {
  const modules = new Map<string, string>();
  const fileByQueryName = new Map<string, string>();
  for (const [file, source] of files) modules.set(file.replace(/\.sql$/, ".gen.ts"), queryModule(file, source, fileByQueryName, tables));
  return modules;
}

/** Module text of a single query file; duplicate names are also rejected across files via `fileByQueryName`. */
function queryModule(file: string, source: string, fileByQueryName: Map<string, string>, tables?: TableColumns): string {
  if (!QUERY_FILE.test(file)) throw new Error(`${file}: query files live in src/queries/`);
  let text = `// Generated by \`bun run db:codegen\` from ${file}. Do not edit.\nimport { defineQuery } from "../core/sql/query";\n`;
  // Split result: [preamble, name1, sql1, name2, sql2, …].
  const [preamble = "", ...blocks] = source.split(/^-- name: *(\S+) *$/m);
  if (preamble.replace(/^--.*$/gm, "").trim() || !blocks.length) throw new Error(`${file}: SQL must follow a "-- name: <identifier>" line`);
  for (let i = 0; i < blocks.length; i += 2) {
    const name = blocks[i] as string;
    if (!QUERY_NAME.test(name)) throw new Error(`${file}: query name ${name} must match ${QUERY_NAME}`);
    const previous = fileByQueryName.get(name);
    if (previous) throw new Error(`${file}: duplicate query ${name} (also in ${previous})`);
    fileByQueryName.set(name, file);
    text += queryExport(file, name, blocks[i + 1] as string, tables);
  }
  return text;
}

function queryExport(file: string, name: string, sql: string, tables?: TableColumns): string {
  try {
    const [query] = compile(sql.trim(), false, undefined, tables);
    return `\nexport const ${name} = defineQuery(${JSON.stringify(query?.parts)}, ${query?.requiresTransaction}, ${query?.readOnly});\n`;
  } catch (error) {
    throw new Error(`${file} ${name}: ${(error as Error).message}`);
  }
}

/** The migrations folder accepts only `.sql`, the seeds folder accepts `.sql` and `.ts`; both are flat (no subfolders). */
const SOURCES = [
  { dir: "src/migrations", ts: false },
  { dir: "src/seeds", ts: true },
];

/** The folder's sorted source files as `[id, ts, text]` (`undefined` if the folder is missing); a name that does not match the format is an error. */
async function readSources(root: string, dir: string, ts: boolean) {
  const entries = await readdir(`${root}/${dir}`).catch(() => undefined);
  if (!entries) return undefined;
  const names = entries.filter((name) => name.endsWith(".sql") || (ts && name.endsWith(".ts") && name !== "index.gen.ts")).sort();
  const bad = names.find((name) => !SOURCE_FILE.test(name) || (!ts && !name.endsWith(".sql")));
  if (bad) throw new Error(`${dir}/${bad}: name must be <yyyyMMddHHmmss>_<snake_name>.${ts ? "sql or .ts" : "sql"}`);
  const read = async (name: string) => [name.replace(/\.(sql|ts)$/, ""), name.endsWith(".ts"), await Bun.file(`${root}/${dir}/${name}`).text()] as const;
  return Promise.all(names.map(read));
}

/** Import list: SQL as a text import (not compiled; a new empty template is also listed), TS as a module + the checksum at codegen time. */
function sourceList(dir: string, sources: readonly (readonly [string, boolean, string])[]) {
  const imports = sources.map(([id, ts], i) => (ts ? `import m${i} from "./${id}";\n` : `import m${i} from "./${id}.sql" with { type: "text" };\n`));
  const entries = sources.map(([id, ts, text], i) => `\n  ["${id}", ${ts ? `{ checksum: "${checksum(text)}", run: m${i} }` : `m${i}`}],`);
  const list = `export default [${entries.join("")}${sources.length ? "\n" : ""}] as const;\n`;
  return `// Generated by \`bun run db:codegen\` from ${dir}. Do not edit.\n${imports.join("")}\n${list}`;
}

/** Generated modules expected under `root`: queries, migration and seed lists, and folded table types. */
export async function codegen(root: string): Promise<Map<string, string>> {
  const modules = new Map<string, string>();
  for await (const path of new Glob("src/{migrations,seeds}/*/*").scan(root)) throw new Error(`${path}: migrations and seeds are flat folders`);
  // `*` in queries is expanded from the folded migration tables: migrations first.
  let tables: TableColumns | undefined;
  for (const { dir, ts } of SOURCES) {
    const sources = await readSources(root, dir, ts);
    if (!sources) continue;
    modules.set(`${dir}/index.gen.ts`, sourceList(dir, sources));
    if (ts) {
      compileSeeds(sources.map(([id, isTs, text]) => [id, isTs ? { checksum: checksum(text), run: async () => {} } : text]));
      continue;
    }
    const migrations = compileMigrations(sources.map(([id, , text]) => [id, text]));
    const shapes = foldTables(migrations.flatMap((m) => m.up.statements));
    tables = shapes.tables;
    for (const [path, text] of tableModules(shapes)) modules.set(path, text);
  }
  const paths = (await Array.fromAsync(new Glob("src/queries/**/*.sql").scan(root))).sort();
  const files = await Promise.all(paths.map(async (path) => [path, await Bun.file(`${root}/${path}`).text()] as const));
  for (const [path, text] of generate(files, tables)) modules.set(path, text);
  return modules;
}

/** Generated files that are missing, outdated, hand-edited or orphaned, and other callers of defineQuery (tests excluded). */
export async function staleFiles(root: string): Promise<string[]> {
  const expected = await codegen(root);
  const stale = new Set(expected.keys()); // removed once found unchanged
  for await (const path of new Glob("src/**/*.ts").scan(root)) {
    if (path.startsWith("src/__tests__/")) continue;
    const text = await Bun.file(`${root}/${path}`).text();
    const valid = path.endsWith(".gen.ts") ? expected.get(path) === text : mayDefineQuery.test(path) || !text.includes("defineQuery");
    if (valid) stale.delete(path);
    else stale.add(path);
  }
  return [...stale].sort();
}

/** Writes the generated files and removes those whose source was deleted. */
export async function writeGenerated(root: string) {
  const modules = await codegen(root);
  for await (const path of new Glob("src/{queries,migrations,seeds,tables}/**/*.gen.ts").scan(root)) if (!modules.has(path)) await rm(`${root}/${path}`);
  for (const [path, text] of modules) await Bun.write(`${root}/${path}`, text);
}

type SourceOptions = { name: string; now?: Date; root?: string };

/** A new source file (with the UTC prefix from `now`, which must be greater than the last file's prefix) and the updated folder list. */
async function createSource(dir: string, ext: "sql" | "ts", source: string, { name, now = new Date(), root = "." }: SourceOptions) {
  if (!MIGRATION_NAME.test(name)) throw new AppError("USAGE", "Name must be snake_case, e.g. create_students");
  const sources = (await readSources(root, dir, dir === "src/seeds")) ?? [];
  const id = `${migrationPrefix(now)}_${name}`;
  const last = sources.at(-1)?.[0];
  if (last && id.slice(0, 14) <= last.slice(0, 14))
    throw new AppError("MIGRATION_INVALID", `Timestamp ${id.slice(0, 14)} is not after ${last}; order must follow IDs`);
  const path = `${dir}/${id}.${ext}`;
  await Bun.write(`${root}/${path}`, source);
  await Bun.write(`${root}/${dir}/index.gen.ts`, sourceList(dir, [...sources, [id, ext === "ts", source]]));
  return { id, path };
}

/** A new migration file (an empty template if `source` is absent; `pull` supplies content) and the list; table types come from `codegen`. */
export async function createMigration({ source = "--up\n\n--down\n", ...options }: SourceOptions & { source?: string }) {
  return createSource("src/migrations", "sql", source, options);
}

/** A new seed file (SQL: an empty DML template, `kind: "ts"`: a default function) and the list. */
export async function createSeed({ kind = "sql", ...options }: SourceOptions & { kind?: "sql" | "ts" }) {
  const source =
    kind === "ts"
      ? 'import type { SeedContext } from "../management";\n\nexport default async function seed(_context: SeedContext): Promise<void> {}\n'
      : "-- INSERT / UPDATE / DELETE; table names without a schema.\n";
  return createSource("src/seeds", kind, source, options);
}

if (import.meta.main) {
  try {
    const stale = process.argv.includes("--check") ? await staleFiles(".") : (await writeGenerated("."), []);
    if (stale.length) throw new Error(`Stale or hand-edited generated files; run \`bun run db:codegen\`:\n${stale.join("\n")}`);
  } catch (error) {
    console.error((error as Error).message);
    process.exit(1);
  }
}
