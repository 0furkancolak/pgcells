import { afterAll, beforeAll, expect } from "bun:test";
import { bootstrap, type Management, migrateTenant, provisionTenant } from "../../management";
import { openManagementSession, withTenantLock } from "../../core/operations/locks";
import { tenantMigrations } from "../../core/migrations/registry";
import { getMove, resumeMove, rollbackMove, startMove } from "../../core/tools/move";
import { createTestManagement, enabled, integration, q, removeTenants, uniqueEmail } from "./helpers";

let app: Management;
const drained = true;
const prefix = `recovery-${crypto.randomUUID().replaceAll("-", "").slice(0, 12)}`;
beforeAll(async () => {
  if (enabled) {
    app = createTestManagement();
    await bootstrap(app);
  }
});
afterAll(async () => {
  if (!app) return;
  try {
    await removeTenants(app, prefix);
  } finally {
    await app.close();
  }
});
async function provision(suffix: string) {
  const id = `${prefix}-${suffix.replaceAll("_", "-")}`;
  await provisionTenant(app, id, "db0");
  return id;
}
/** A move-record trigger; names and bodies are generated by this test, never external input. */
async function trigger(moveId: string, name: string, body: string) {
  const db = app.pools.platform;
  const fn = `platform.${name}`;
  await db.exec(
    `CREATE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.id='${moveId}'::uuid THEN ${body} END IF; RETURN NEW; END $$; CREATE TRIGGER ${name} BEFORE UPDATE ON platform.moves FOR EACH ROW EXECUTE FUNCTION ${fn}()`,
  );
  return () => db.exec(`DROP TRIGGER ${name} ON platform.moves; DROP FUNCTION ${fn}()`);
}
// A real database failure tests recovery without exposing checkpoint hooks in production.
const failPhase = (moveId: string, phase: string) =>
  trigger(
    moveId,
    `fault_${moveId.replaceAll("-", "")}`,
    `IF NEW.phase='${phase}' THEN RAISE EXCEPTION 'injected checkpoint crash'; END IF;`,
  );
async function planned(suffix: string) {
  const id = await provision(suffix);
  const before = await app.platform.get(id);
  const target = app.pools.node("db1");
  await target.exec(`CREATE SCHEMA ${q(before.schemaName)}`);
  let moveId = "";
  await expect(
    startMove(app, id, "db1", drained, (move) => {
      moveId = move.id;
    }),
  ).rejects.toThrow("Target schema exists");
  await target.exec(`DROP SCHEMA ${q(before.schemaName)}`);
  return { id, before, targetId: "db1", moveId, target };
}
integration("tenant management excludes concurrent commands", async () => {
  const id = await provision("lock");
  await withTenantLock(app, id, async () => {
    await expect(migrateTenant(app, id)).rejects.toThrow("owns this tenant");
  });
});
integration("dedicated management session refuses lost locks", async () => {
  const lock = await openManagementSession(app, "db0", `${prefix}-session`);
  try {
    await lock.db.query("SELECT pg_advisory_unlock_all()");
    await expect(lock.assertOwned()).rejects.toThrow("lost its lock");
  } finally {
    await lock.close();
  }
});
integration("checksum drift fails directly and can be repaired", async () => {
  const id = await provision("drift");
  const p = await app.platform.get(id);
  const db = app.pools.node(p.databaseId);
  const ledger = q(p.schemaName, "_migrations");
  const last = tenantMigrations.at(-1)?.id;
  const [original] = await db.query<{ checksum: string }>(`SELECT checksum FROM ${ledger} WHERE id=$1`, [last]);
  if (!original) throw new Error("Missing migration");
  await db.query(`UPDATE ${ledger} SET checksum='wrong' WHERE id=$1`, [last]);
  await expect(migrateTenant(app, id)).rejects.toMatchObject({ code: "MIGRATION_DRIFT" });
  await db.query(`UPDATE ${ledger} SET checksum=$1 WHERE id=$2`, [original.checksum, last]);
  await migrateTenant(app, id);
});
integration("transactional migration failure rolls back DDL and ledger", async () => {
  const id = `${prefix}-partial`;
  const p = await app.platform.create(id, "db0");
  const db = app.pools.node(p.databaseId);
  // İlk migration `users`'ı önce, `teachers`'ı sonra kurar: çakışan `teachers` onu yarıda düşürür.
  await db.exec(`CREATE SCHEMA ${q(p.schemaName)}; CREATE TABLE ${q(p.schemaName, "teachers")} (id uuid PRIMARY KEY)`);
  await expect(provisionTenant(app, id, p.databaseId)).rejects.toThrow();
  expect(
    await db.query("SELECT to_regclass($1) IS NOT NULL AS exists", [`${p.schemaName}.users`]),
  ).toEqual([{ exists: false }]);
  await db.exec(`DROP TABLE ${q(p.schemaName, "teachers")}`);
  await provisionTenant(app, id, p.databaseId);
  expect((await app.platform.get(id)).status).toBe("active");
});
integration("owned maintenance rolls back even before its checkpoint commits", async () => {
  const { id, moveId, before } = await planned("rollback");
  const clean = await failPhase(moveId, "maintenance");
  try {
    await expect(resumeMove(app, moveId, drained)).rejects.toThrow("injected checkpoint crash");
  } finally {
    await clean();
  }
  expect((await getMove(app, moveId)).phase).toBe("planned");
  await rollbackMove(app, moveId, drained);
  expect((await app.platform.get(id)).status).toBe("active");
  expect((await app.platform.get(id)).databaseId).toBe(before.databaseId);
  await expect(resumeMove(app, moveId, drained)).rejects.toThrow("terminal");
});
integration("failure after cutover resumes activation and refuses rollback", async () => {
  const { id, moveId, before, targetId, target } = await planned("cutover");
  await app.pools
    .node(before.databaseId)
    .query(`INSERT INTO ${q(before.schemaName, "users")} (name,email) VALUES ('Retained',$1)`, [uniqueEmail()]);
  const clean = await failPhase(moveId, "cutover");
  try {
    await expect(resumeMove(app, moveId, drained)).rejects.toThrow("injected checkpoint crash");
  } finally {
    await clean();
  }
  await expect(rollbackMove(app, moveId, drained)).rejects.toThrow("reverse data migration");
  await resumeMove(app, moveId, drained);
  expect((await app.platform.get(id)).databaseId).toBe(targetId);
  expect(await target.query(`SELECT name FROM ${q(before.schemaName, "users")}`)).toEqual([{ name: "Retained" }]);
});
integration("placement owner resumes a pre-cutover failure", async () => {
  const { id, moveId, targetId } = await planned("resume");
  const clean = await failPhase(moveId, "copying");
  try {
    await expect(resumeMove(app, moveId, drained)).rejects.toThrow("injected checkpoint crash");
  } finally {
    await clean();
  }
  await resumeMove(app, moveId, drained);
  expect((await app.platform.get(id)).databaseId).toBe(targetId);
});

/** A retained target schema with a sentinel row that must survive refused moves. */
async function sentinel(target: Management["pools"]["platform"], schema: string) {
  await target.exec(
    `CREATE SCHEMA ${q(schema)}; CREATE TABLE ${q(schema, "sentinel")} (value text); INSERT INTO ${q(schema, "sentinel")} VALUES ('retained')`,
  );
  return async () => (await target.query<{ value: string }>(`SELECT value FROM ${q(schema, "sentinel")}`))[0]?.value;
}

integration("target reservation must match both operation and schema", async () => {
  const { id, moveId, before, target } = await planned("reservation");
  const retained = await sentinel(target, before.schemaName);
  await target.query("INSERT INTO platform.move_targets(tenant_id,operation_id,schema_name) VALUES ($1,$2,'different_schema')", [
    id,
    moveId,
  ]);
  try {
    for (const foreignOperation of [false, true]) {
      if (foreignOperation)
        await target.query("UPDATE platform.move_targets SET operation_id=$1,schema_name=$2 WHERE tenant_id=$3", [
          crypto.randomUUID(),
          before.schemaName,
          id,
        ]);
      await expect(resumeMove(app, moveId, drained)).rejects.toMatchObject({ code: "TARGET_RESERVED" });
      expect(await retained()).toBe("retained");
      expect((await app.platform.get(id)).status).toBe("active");
    }
  } finally {
    // Paylaşılan DB'de yarım taşıma kalmasın (sonraki dosyalarda doctor ve migrate-all onu hata sayar): sahte rezervasyon silinir,
    // taşıma geri alınır.
    await target.query("DELETE FROM platform.move_targets WHERE tenant_id=$1", [id]);
    await rollbackMove(app, moveId, drained);
  }
  expect((await app.platform.get(id)).status).toBe("active");
});

integration("unfinished moves block new intents until rolled back or completed", async () => {
  const { id, moveId, targetId, before } = await planned("new_intent");
  // An unfinished move blocks new intents until it is resumed or rolled back.
  await expect(startMove(app, id, targetId, drained)).rejects.toMatchObject({
    code: "MOVE_UNFINISHED",
    message: expect.stringContaining(moveId),
  });
  // A planned target collision already establishes intent ownership and may
  // be rolled back without having entered maintenance.
  await rollbackMove(app, moveId, drained);
  const next = await startMove(app, id, targetId, drained);
  expect(next.status).toBe("completed");
  expect(next.id).not.toBe(moveId);
  expect((await app.platform.get(id)).databaseId).toBe(targetId);
  let reverseId = "";
  await expect(
    startMove(app, id, before.databaseId, drained, (move) => {
      reverseId = move.id;
    }),
  ).rejects.toThrow("Target schema exists");
  await rollbackMove(app, reverseId, drained);
  expect((await app.platform.get(id)).databaseId).toBe(targetId);
  expect((await app.platform.get(id)).status).toBe("active");
});

integration("owned target rebuild rechecks placement and remains retryable", async () => {
  const { id, moveId, before, targetId, target } = await planned("rebuild");
  const retained = await sentinel(target, before.schemaName);
  await target.query("INSERT INTO platform.move_targets(tenant_id,operation_id,schema_name) VALUES ($1,$2,$3)", [
    id,
    moveId,
    before.schemaName,
  ]);
  // A checkpoint-side state change exercises the final check before DROP,
  // after the initial placement claim already succeeded.
  const clean = await trigger(
    moveId,
    `changed_${moveId.replaceAll("-", "")}`,
    "IF NEW.phase='maintenance' THEN UPDATE platform.placements SET status='active' WHERE tenant_id=NEW.tenant_id; END IF;",
  );
  try {
    await expect(resumeMove(app, moveId, drained)).rejects.toMatchObject({ code: "PLACEMENT_CONFLICT" });
    expect(await retained()).toBe("retained");
  } finally {
    await clean();
  }
  await resumeMove(app, moveId, drained);
  expect((await app.platform.get(id)).databaseId).toBe(targetId);
  expect(
    await target.query("SELECT to_regclass($1) IS NOT NULL AS exists", [`${before.schemaName}.sentinel`]),
  ).toEqual([{ exists: false }]);
});
