test("check enums follow constraint names; table primary keys imply NOT NULL", () => {
  const shapes = fold(
    "CREATE TABLE t (a text, b text, PRIMARY KEY (a), CONSTRAINT b_kind CHECK (b IN ('x')))",
    "ALTER TABLE t DROP CONSTRAINT b_kind; ALTER TABLE t ADD CONSTRAINT a_kind CHECK (a IN ('p', 'q'))",
  );
  expect(shapes.tables.get("t")).toEqual([
    { name: "a", type: "text", arrayDepth: 0, notNull: true, hasDefault: false, check: { name: "a_kind", values: ["p", "q"] } },
    { name: "b", type: "text", arrayDepth: 0, notNull: false, hasDefault: false },
  ]);
});

test("codegen rejects DDL it cannot fold instead of guessing", () => {
  for (const ups of [
    ["ALTER TABLE missing ADD COLUMN x text"],
    ["CREATE TABLE t (a text)", "CREATE TABLE t (a text)"],
    ["CREATE TABLE t (a text)", "ALTER TABLE t RENAME COLUMN b TO c"],
    ["CREATE TABLE t (a text)", "DROP TABLE u"],
    ["CREATE TABLE student (a text); CREATE TABLE students (a text)"],
  ])
    expect(() => modules(...ups), ups.join(" / ")).toThrow(/SQL_UNSUPPORTED/);
});

test("generated repository tables parse driver values", () => {
  const id = crypto.randomUUID();
  const user = { id, name: "Ada", email: "ada@x", emailVerified: true, image: null, twoFactorEnabled: null, createdAt: new Date(0), updatedAt: new Date(0) };
  expect(userRow.parse(user)).toEqual(user);
  // Varsayılanı olan sütunlar (id dahil: gen_random_uuid()) insert şemasında isteğe bağlıdır.
  expect(userInsert.parse({ name: "Ada", email: "ada@x" })).toEqual({ name: "Ada", email: "ada@x" });
  expect(() => userRow.parse({ ...user, id: "not-a-uuid" })).toThrow();
  expect(() => userRow.parse({ ...user, emailVerified: undefined })).toThrow();
  expect(() => userInsert.parse({ name: "Ada" })).toThrow();
});
