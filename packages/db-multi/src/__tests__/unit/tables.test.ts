test("snake_case columns get camelCase schema keys and a static column map; camelCase collisions reject", () => {
  const out = modules(`CREATE TABLE t (first_name text NOT NULL, "emailVerified" boolean, "odd key" text)`).get("src/tables/tenant/t.gen.ts");
  expect(out).toContain("  firstName: z.string(),\n");
  expect(out).toContain(`export const tColumns = {\n  firstName: "first_name",\n  emailVerified: "emailVerified",\n  "odd key": "odd key",\n} as const;\n`);
  expect(sessionColumns).toEqual({
    id: "id",
    expiresAt: "expires_at",
    token: "token",
    createdAt: "created_at",
    updatedAt: "updated_at",
    ipAddress: "ip_address",
    userAgent: "user_agent",
    userId: "user_id",
  });
  const session = { id: crypto.randomUUID(), expiresAt: new Date(1), token: "t", createdAt: new Date(0), updatedAt: new Date(0), ipAddress: null, userAgent: null, userId: crypto.randomUUID() };
  expect(sessionRow.parse(session)).toEqual(session);
  expect(() => modules(`CREATE TABLE t (first_name text, "firstName" text)`)).toThrow(/SQL_UNSUPPORTED.*unique camelCase keys \(firstName\)/);
});

const fold = (...ups: string[]) =>
  foldTables(
    compileMigrations(
      "tenant",
      ups.map((up, i) => [`2026091514301${i}_m`, `--up\n${up}\n--down\n`]),
    ).flatMap((m) => m.up.statements),
  );
const modules = (...ups: string[]) => tableModules("tenant", fold(...ups));

