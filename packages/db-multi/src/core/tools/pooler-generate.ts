/** PgBouncer configuration for a node list: the production starting point of docs/guides/connections.md (section 5), deterministic and free of secrets.
 * `[databases]` aliases are the node ids, so the application's `DATABASE_URLS` entry for `db1` points at the alias `db1` on the pooler; replicas become
 * `db1_ro1`, `db1_ro2`, … in their configured order. The pooler's backends are the direct URLs that management already uses. */
import type { DatabaseNode } from "../config";
import { AppError } from "../errors";

export interface PoolerGenerateOptions {
  nodes: readonly DatabaseNode[];
  /** PgBouncer instances that will share the load; informs `max_db_connections` only through `defaultPoolSize`, and the header comment. */
  poolers?: number;
  defaultPoolSize?: number;
  maxClientConn?: number;
  /** The application's `statementTimeoutMs`: `query_wait_timeout` is set above its answer deadline (statement timeout + 1.5 s). */
  statementTimeoutMs?: number;
  listenPort?: number;
  /** PgBouncer's `max_prepared_statements` (default 0: pgcells never uses named prepared statements; 1.21+ can track them when above 0). */
  maxPreparedStatements?: number;
  /** `false` writes `sslmode = disable` for both client and server sides: local containers only, never production. Default `true`. */
  tls?: boolean;
}

export type PoolerFiles = Record<"pgbouncer.ini" | "userlist.txt", string>;

interface Backend {
  alias: string;
  host: string;
  port: string;
  dbname: string;
  user: string;
}

function backend(alias: string, url: string): Backend {
  const parsed = URL.parse(url);
  if (!parsed || !parsed.hostname) throw new AppError("INVALID_CONFIG", `Database URL for ${alias} is not valid`);
  return {
    alias,
    host: parsed.hostname,
    port: parsed.port || "5432",
    dbname: decodeURIComponent(parsed.pathname.replace(/^\//, "")),
    user: decodeURIComponent(parsed.username),
  };
}

const positiveInteger = (value: number | undefined, fallback: number, name: string) => {
  const number = value ?? fallback;
  if (!Number.isInteger(number) || number < 1) throw new AppError("INVALID_CONFIG", `${name} must be a positive whole number`);
  return number;
};

/** The same input always gives the same bytes (nodes are sorted by id), so a file in version control can be compared with `--check`. */
export function generatePoolerFiles(options: PoolerGenerateOptions): PoolerFiles {
  const poolers = positiveInteger(options.poolers, 2, "poolers");
  const defaultPoolSize = positiveInteger(options.defaultPoolSize, 20, "defaultPoolSize");
  const maxClientConn = positiveInteger(options.maxClientConn, 2000, "maxClientConn");
  const statementTimeoutMs = positiveInteger(options.statementTimeoutMs, 5000, "statementTimeoutMs");
  const listenPort = positiveInteger(options.listenPort, 6432, "listenPort");
  const tls = options.tls ?? true;
  const maxPreparedStatements = options.maxPreparedStatements ?? 0;
  if (!Number.isInteger(maxPreparedStatements) || maxPreparedStatements < 0) throw new AppError("INVALID_CONFIG", "maxPreparedStatements must be a whole number, zero or more");
  if (!options.nodes.length) throw new AppError("INVALID_CONFIG", "At least one node is needed");

  const nodes = [...options.nodes].sort((a, b) => Number(a.id.slice(2)) - Number(b.id.slice(2)));
  const backends = nodes.flatMap((node) => [
    backend(node.id, node.url),
    ...node.replicas.map((url, index) => backend(`${node.id}_ro${index + 1}`, url)),
  ]);
  const users = [...new Set(backends.map((entry) => entry.user).filter(Boolean))].sort();
  const queryWaitTimeout = Math.ceil((statementTimeoutMs + 1500) / 1000) + 1;
  const databases = backends.map((entry) => `${entry.alias} = host=${entry.host} port=${entry.port} dbname=${entry.dbname} pool_size=${defaultPoolSize}`);

  const ini = `; Generated by pgcells (tools pooler generate). Starting values: measure, then adjust. See docs/guides/connections.md.
; Sized for ${poolers} PgBouncer instance(s); run each with this file behind an L4 load balancer.

[databases]
; One alias per node (the application's DATABASE_URLS entry points at the alias) and one per replica.
${databases.join("\n")}

[pgbouncer]
; pgcells requires transaction pooling.
pool_mode = transaction
listen_addr = 0.0.0.0
listen_port = ${listenPort}
; Lets several pgbouncer processes share one host.
so_reuseport = 1

max_client_conn = ${maxClientConn}
default_pool_size = ${defaultPoolSize}
min_pool_size = ${Math.min(5, defaultPoolSize)}
reserve_pool_size = ${Math.min(5, defaultPoolSize)}
reserve_pool_timeout = 3
max_db_connections = ${defaultPoolSize * 2}

; Timeouts: query_wait_timeout stays above the application's answer deadline (statementTimeoutMs ${statementTimeoutMs} + 1 s + 0.5 s).
query_wait_timeout = ${queryWaitTimeout}
server_connect_timeout = 5
server_login_retry = 1
client_login_timeout = 10
idle_transaction_timeout = 15
server_idle_timeout = 60
server_lifetime = 1800
tcp_keepalive = 1

; ${maxPreparedStatements === 0 ? "Named prepared statements are not used." : "Tracks named prepared statements (PgBouncer 1.21+); pgcells itself does not use them."}
max_prepared_statements = ${maxPreparedStatements}

auth_type = scram-sha-256
auth_file = /etc/pgbouncer/userlist.txt
${tls ? "; TLS is required on both sides; point client_tls_* and server_tls_ca_file at your certificates." : "; TLS is OFF (--no-tls): local containers only."}
client_tls_sslmode = ${tls ? "require" : "disable"}
server_tls_sslmode = ${tls ? "verify-full" : "disable"}

admin_users = pgbouncer_admin
stats_users = pgbouncer_stats
`;

  const list = `; Generated by pgcells (tools pooler generate). It holds no secrets: replace each placeholder with the user's SCRAM verifier
; (SELECT rolpassword FROM pg_authid WHERE rolname = '<user>') and keep the file out of version control.
; PgBouncer logs in to every backend with that verifier, so all backends must hold the same verifier for the user
; (or give per-database credentials in [databases] instead).
${users.map((user) => `"${user}" "SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>"`).join("\n")}
"pgbouncer_admin" "SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>"
"pgbouncer_stats" "SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>"
`;
  return { "pgbouncer.ini": ini, "userlist.txt": list };
}

/** Lines that differ between the expected and the actual file (line numbers are 1-based); at most 20 are reported. Line endings are ignored. */
export function compareLines(expected: string, actual: string): { line: number; expected: string; actual: string }[] {
  const [want, have] = [expected, actual].map((text) => text.replaceAll("\r\n", "\n").split("\n"));
  const differences: { line: number; expected: string; actual: string }[] = [];
  for (let i = 0; i < Math.max(want?.length ?? 0, have?.length ?? 0) && differences.length < 20; i++)
    if (want?.[i] !== have?.[i]) differences.push({ line: i + 1, expected: want?.[i] ?? "", actual: have?.[i] ?? "" });
  return differences;
}
